import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const SRC_DIR = 'assets-src/photos'
const OUT_DIR = 'public/img'
const MANIFEST_PATH = 'src/lib/images.gen.ts'
const TARGET_WIDTHS = [480, 768, 1080, 1600, 2400] as const
const JPEG_FALLBACK_MAX = 1080
const SKIP = /^(favicon|thp_logo|russ-ward)/i
const IMG_EXT = /\.(jpe?g|png|webp|avif)$/i

async function collectFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  const files: string[] = []
  for (const e of entries) {
    const full = path.join(dir, e.name)
    if (e.isDirectory()) {
      files.push(...(await collectFiles(full)))
    } else if (IMG_EXT.test(e.name) && !SKIP.test(e.name)) {
      files.push(full)
    }
  }
  return files.sort()
}

const files = await collectFiles(SRC_DIR)
await rm(OUT_DIR, { recursive: true, force: true })

const manifest: Record<
  string,
  {
    slug: string
    width: number
    height: number
    widths: number[]
    jpegFallbackWidth: number
    lqip: string
  }
> = {}

let bytesBefore = 0
let bytesAfterAll = 0
let bytesAfterBestWebp = 0
let bytesAfterBestAvif = 0

for (const file of files) {
  const slug = path.basename(file, path.extname(file)).toLowerCase()
  const srcStat = await stat(file)
  bytesBefore += srcStat.size

  const meta = await sharp(file).metadata()
  const width = meta.width!
  const height = meta.height!
  const isProducto = file.replace(/\\/g, '/').includes('/productos/')
  const maxW = isProducto ? Math.max(width, 1080) : width
  const widths = TARGET_WIDTHS.filter((w) => w <= maxW)
  if (widths.length === 0) widths.push(width as 480)

  const outSlugDir = path.join(OUT_DIR, slug)
  await mkdir(outSlugDir, { recursive: true })

  const jpegCap = Math.min(JPEG_FALLBACK_MAX, width)
  const jpegFallbackWidth =
    [...widths].reverse().find((w) => w <= jpegCap) ?? widths[widths.length - 1]!

  for (const w of widths) {
    const pipeline = sharp(file).resize({ width: w, withoutEnlargement: !isProducto })
    const [avifInfo, webpInfo] = await Promise.all([
      pipeline.clone().avif({ quality: 52, effort: 4 }).toFile(path.join(outSlugDir, `${w}.avif`)),
      pipeline.clone().webp({ quality: 75 }).toFile(path.join(outSlugDir, `${w}.webp`)),
    ])
    bytesAfterAll += avifInfo.size + webpInfo.size
    if (w === widths[widths.length - 1]) {
      bytesAfterBestAvif += avifInfo.size
      bytesAfterBestWebp += webpInfo.size
    }
  }

  const jpegPipeline = sharp(file).resize({
    width: jpegFallbackWidth,
    withoutEnlargement: !isProducto,
  })
  const jpgInfo = await jpegPipeline
    .jpeg({ quality: 78, mozjpeg: true })
    .toFile(path.join(outSlugDir, `${jpegFallbackWidth}.jpg`))
  bytesAfterAll += jpgInfo.size

  for (const name of await readdir(outSlugDir)) {
    const m = /^(\d+)\.jpg$/.exec(name)
    if (m && Number(m[1]) !== jpegFallbackWidth) {
      await rm(path.join(outSlugDir, name))
    }
  }

  const lqipBuf = await sharp(file).resize({ width: 16 }).webp({ quality: 40 }).toBuffer()
  const lqip = `data:image/webp;base64,${lqipBuf.toString('base64')}`

  const maxOutW = isProducto ? Math.max(width, widths[widths.length - 1]) : width
  const maxOutH = Math.round((height * maxOutW) / width)
  manifest[slug] = {
    slug,
    width: maxOutW,
    height: maxOutH,
    widths: [...widths],
    jpegFallbackWidth,
    lqip,
  }
}

const sortedEntries = Object.keys(manifest)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])},`)
  .join('\n')

const code = `// Auto-generated by scripts/images.ts — do not edit manually.
export const images = {
${sortedEntries}
} as const

export type ImageSlug = keyof typeof images
export type ImageMeta = (typeof images)[ImageSlug]
`

await mkdir(path.dirname(MANIFEST_PATH), { recursive: true })
await writeFile(MANIFEST_PATH, code)

const fmt = (b: number) => `${(b / 1024 / 1024).toFixed(2)} MB (${b.toLocaleString()} B)`
console.log(`Processed ${files.length} source images -> ${OUT_DIR}`)
console.log(`Source total (16 photos): ${fmt(bytesBefore)}`)
console.log(`Max-width AVIF set (16 photos): ${fmt(bytesAfterBestAvif)}`)
console.log(`Max-width WebP set (16 photos): ${fmt(bytesAfterBestWebp)}`)
console.log(`All widths x 3 formats total: ${fmt(bytesAfterAll)}`)
